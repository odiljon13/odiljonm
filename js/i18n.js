// Current active language state
let currentLang = localStorage.getItem("site_lang") || "uz";
if (!translations[currentLang]) {
  currentLang = "uz";
}

function getLanguage() {
  return currentLang;
}

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem("site_lang", lang);
    applyTranslations();
  }
}

function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (translations["uz"] && translations["uz"][key]) {
    return translations["uz"][key];
  }
  return key;
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      const translation = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("placeholder")) {
          el.placeholder = translation;
        } else {
          el.value = translation;
        }
      } else {
        el.textContent = translation;
      }
    }
  });

  // Update language selector dropdown if exists
  const langSelectors = document.querySelectorAll(".lang-selector-select");
  langSelectors.forEach(sel => {
    if (sel.value !== currentLang) {
      sel.value = currentLang;
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
});

